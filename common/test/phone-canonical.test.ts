/**
 * Телефон приводится к канонической форме НА ГРАНИЦЕ API.
 *
 * ⚠️ Написан по факту дефекта: `shared/phone` не импортировался
 * сервером ни разу. Нормализовала номер только форма бронирования,
 * а стойка, лист ожидания, walk-in и запросы по 152-ФЗ писали и искали
 * то, что пришло. Проверено на живом стенде: заказ с «89991234567»
 * создавался рядом с существующим «+79991234567».
 *
 * Последствия, ради которых тест существует:
 *   — два клиента вместо одного: уникальный индекс (tenant_id, phone)
 *     их не связывает;
 *   — лимит активных броней и счётчик неявок обходятся сменой формата;
 *   — стойка не находит заказ по телефону;
 *   — выгрузка и удаление по 152-ФЗ возвращают не все данные субъекта.
 */
import { describe, expect, it } from 'vitest'
import { canonicalPhone, isValidPhone } from '../src/phone.js'

describe('канонический телефон', () => {
  it('⚠️ все бытовые записи одного номера дают ОДНУ строку', () => {
    const same = [
      '+79991234567',
      '89991234567',
      '79991234567',
      '+7 999 123-45-67',
      '8 (999) 123 45 67',
      '  +7-999-123-45-67  ',
    ]
    const canon = same.map(canonicalPhone)

    // Иначе каждая форма записи заводит своего клиента.
    expect(new Set(canon).size, `разошлись: ${canon.join(' | ')}`).toBe(1)
    expect(canon[0]).toBe('+79991234567')
  })

  it('мусор не превращается в номер', () => {
    // ⚠️ Пустая строка, а не «почти номер»: неверный ввод должен быть
    // отвергнут схемой, а не записан в БД в исправленном виде.
    for (const bad of ['', 'абв', '123', '+7999', 'р8987987987989']) {
      expect(canonicalPhone(bad), bad).toBe('')
    }
  })

  it('канон всегда проходит собственную проверку', () => {
    // Свойство, без которого нормализация на границе бессмысленна:
    // то, что записано, обязано считаться валидным при чтении.
    for (const raw of ['89991234567', '+7 999 123-45-67']) {
      expect(isValidPhone(canonicalPhone(raw)), raw).toBe(true)
    }
  })

  it('⚠️ повторная нормализация ничего не меняет', () => {
    // Функция применяется и при записи, и при поиске — её вывод
    // обязан быть для неё допустимым входом.
    const once = canonicalPhone('8 (999) 123-45-67')
    expect(canonicalPhone(once)).toBe(once)
  })
})
